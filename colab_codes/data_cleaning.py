files.download('final_dataset.csv')

import pandas as pd

store_raw = pd.read_excel('/content/sample_data/Final_UT.xls')
gtrend = pd.read_csv('/content/sample_data/vis2_gtrends_data.csv')

gtrend['date']=pd.to_datetime(gtrend['date'], format="%d-%m-%Y")

store_raw.columns = store_raw.columns.str.lower().str.strip()
gtrend.columns = gtrend.columns.str.lower().str.strip()

print(store_raw.columns)

store_raw = store_raw.rename(columns={'item name' : 'item','sale quantity' : 'quantity', 'sale amount':'sales'})

store_raw = store_raw.dropna(subset=['item','quantity'])

store_raw = store_raw[store_raw['item'].str.lower() != 'total']

store_raw['quantity'] = pd.to_numeric(store_raw['quantity'], errors='coerce')
store_raw['sales'] = pd.to_numeric(store_raw['sales'], errors='coerce')

store_raw = store_raw.dropna(subset=['quantity'])

def clean_category(x):
    x = str(x).lower().strip()

    if any(word in x for word in['full sleeves','jacket','sweatshirt','hoodie']):
        return 'long sleeve'
    elif any(word in x for word in['shorts','pants','jeans','pant']):
       return 'lowers'
    elif any(word in x for word in['crew neck','round neck','half','polo']):
        return 'short sleeves'
    elif 'print' in x:
        return 'printed shirt'
    else:
        return 'others'

store_raw['category'] = store_raw['item'].apply(clean_category)

store_raw = store_raw[store_raw['category'] != 'others']

store_raw[['item','category','sales','quantity']].to_csv('store_with_category.csv', index=False)

"""aggregate store data"""

store = store_raw.groupby('category')['quantity'].sum().reset_index()
store.rename(columns={'quantity': 'sales'}, inplace=True)

print("Correct total:", store['sales'].sum())

print("Total qty:", store_raw['quantity'].sum())
print("Rows:", len(store_raw))
print(store_raw.head())

store['category'] = store['category'].replace({
    'long sleeve': 'long sleeves',
    'short sleeve': 'short sleeves'
})

gtrend_long = gtrend.melt(
    id_vars=['date'],
    value_vars=['long sleeves', 'lowers','short sleeves','printed shirt'],
    var_name='category',
    value_name='gtrend'
)

print(store['category'].unique())
print(gtrend_long['category'].unique())

gtrend_long['time_weight'] = gtrend_long.groupby('category')['gtrend'].transform(
    lambda x: x / x.sum()
)

df = pd.merge(store, gtrend_long, on='category')

df = df[['date', 'category', 'sales', 'gtrend', 'time_weight']]

df['sales'] = df['sales'] * df['time_weight']

df['sales'] = df['sales'] * 1000

gtrend_long.groupby('category')['time_weight'].sum()

df.to_csv("final_dataset.csv", index=False)

print(gtrend_long[['category','gtrend','time_weight']].head())

print(df.head())