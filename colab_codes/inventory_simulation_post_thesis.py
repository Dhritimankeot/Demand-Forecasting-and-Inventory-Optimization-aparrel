"""Initial Inventory"""

initial_inventory = 300
lead_time_days = 7

holding_cost_per_unit = 2
stockout_cost_per_unit = 5

"""Category Specific SS"""

safety_stock = {
    'short sleeves': 142.53,
    'long sleeves': 42.54,
    'lowers': 65.73,
    'printed shirt' : 3.78
}

"""Infer Data Frequency"""

def infer_avg_step_days(df_cat):

    date_diffs = (
        df_cat['date'].diff().dt.total_seconds()
        / (3600 * 24)
    )

    avg_days = float(date_diffs.dropna().mean())

    if np.isnan(avg_days) or avg_days <= 0:
        avg_days = 7.0

    return avg_days

"""Inventory Simulation"""

def simulate_base_stock_calendar_lead(
    df_in, pred_col, safety_stock
):

    df_out_list = []

    for cat_val, df_cat in df_in.groupby(
        'category', sort=False
    ):

        df_cat = df_cat.sort_values(
            'date'
        ).reset_index(drop=True)

        # Get category-specific safety stock

        category_safety_stock = safety_stock[cat_val]

        avg_step_days = infer_avg_step_days(df_cat)

        lt_steps_equiv = (
            float(lead_time_days) / float(avg_step_days)
        )

        inv_level = float(initial_inventory)

        open_orders = []

        inv_levels = []
        stockout_units_list = []
        fulfilled_units_list = []
        holding_cost_list = []
        stockout_cost_list = []
        orders_placed_list = []
        receipts_list = []
        inv_position_list = []
        target_list = []
        on_order_qty_list = []

        for t_idx in range(len(df_cat)):

            current_date = df_cat.loc[t_idx, 'date']

            # Receive outstanding orders

            received_qty = 0.0

            if open_orders:

                still_open = []

                for ord_rec in open_orders:

                    if ord_rec['arrival_date'] <= current_date:

                        received_qty += float(ord_rec['qty'])

                    else:

                        still_open.append(ord_rec)

                open_orders = still_open

            inv_level += received_qty

            receipts_list.append(received_qty)

            # Actual demand and predicted demand

            sales_val = float(df_cat.loc[t_idx, 'sales'])

            pred_val = float(df_cat.loc[t_idx, pred_col])

            # Fulfil demand

            fulfilled_units = min(inv_level, sales_val)

            stockout_units = max(
                0.0, sales_val - inv_level
            )

            inv_level -= fulfilled_units

            # Calculate costs

            holding_cost_val = (
                inv_level * holding_cost_per_unit
            )

            stockout_cost_val = (
                stockout_units * stockout_cost_per_unit
            )

            # Calculate inventory position

            on_order_qty = sum(
                float(o['qty']) for o in open_orders
            )

            inv_position = inv_level + on_order_qty

            # Forecast demand during lead time

            demand_over_lt = (
                pred_val * lt_steps_equiv
            )

            # Base-stock target with category-specific safety stock

            target = (
                demand_over_lt + category_safety_stock
            )

            # Calculate order quantity

            order_qty = max(
                0.0, target - inv_position
            )

            if order_qty > 0:

                arrival_date = (
                    current_date
                    + pd.Timedelta(days=lead_time_days)
                )

                open_orders.append({
                    'arrival_date': arrival_date,
                    'qty': order_qty
                })

            # Store results

            orders_placed_list.append(order_qty)

            inv_levels.append(inv_level)

            stockout_units_list.append(stockout_units)

            fulfilled_units_list.append(fulfilled_units)

            holding_cost_list.append(holding_cost_val)

            stockout_cost_list.append(stockout_cost_val)

            inv_position_list.append(inv_position)

            target_list.append(target)

            on_order_qty_list.append(on_order_qty)

        # Store category results

        df_cat_out = df_cat.copy()

        df_cat_out['model_pred_col'] = pred_col

        df_cat_out['inventory'] = inv_levels

        df_cat_out['inventory_position'] = inv_position_list

        df_cat_out['target_base_stock'] = target_list

        df_cat_out['on_order_qty'] = on_order_qty_list

        df_cat_out['received'] = receipts_list

        df_cat_out['order_placed'] = orders_placed_list

        df_cat_out['stockout_units'] = stockout_units_list

        df_cat_out['fulfilled_units'] = fulfilled_units_list

        df_cat_out['holding_cost'] = holding_cost_list

        df_cat_out['stockout_cost'] = stockout_cost_list

        df_cat_out['total_cost'] = (
            df_cat_out['holding_cost']
            + df_cat_out['stockout_cost']
        )

        df_cat_out['safety_stock'] = category_safety_stock

        df_out_list.append(df_cat_out)

    return pd.concat(df_out_list, ignore_index=True)

"""PERFORMANCE SUMMARY"""

def summarize_sim(sim_df, model_name):

    total_holding = float(
        sim_df['holding_cost'].sum()
    )

    total_stockout_cost = float(
        sim_df['stockout_cost'].sum()
    )

    total_stockout_units = float(
        sim_df['stockout_units'].sum()
    )

    total_demand = float(
        sim_df['sales'].sum()
    )

    total_cost = (
        total_holding + total_stockout_cost
    )

    fill_rate = (
        1.0 - total_stockout_units / total_demand
        if total_demand > 0 else 0.0
    )

    return {
        'Model': model_name,
        'Total Holding Cost': total_holding,
        'Total Stockout Cost': total_stockout_cost,
        'Total Stockouts': total_stockout_units,
        'Total Cost': total_cost,
        'Fill Rate': fill_rate
    }

"""CATEGORY LEVEL RESULTS"""

def category_table(sim_df, model_name):

    grp = sim_df.groupby(
        'category', as_index=False
    ).agg(
        Safety_Stock=('safety_stock', 'first'),
        Stockouts=('stockout_units', 'sum'),
        HoldingCost=('holding_cost', 'sum'),
        StockoutCost=('stockout_cost', 'sum'),
        Demand=('sales', 'sum')
    )

    grp['Cost'] = (
        grp['HoldingCost'] + grp['StockoutCost']
    )

    grp['Fill Rate'] = (
        1.0 - grp['Stockouts'] / grp['Demand']
    )

    grp['Model'] = model_name

    return grp

"""Running Simulation"""

sim_xgb = simulate_base_stock_calendar_lead(
    df_inv, 'y_pred', safety_stock
)

sim_naive = simulate_base_stock_calendar_lead(
    df_inv, 'y_naive', safety_stock
)

"""Overall Results"""

summary_overall = pd.DataFrame([

    summarize_sim(
        sim_xgb,
        'XGBoost'
    ),

    summarize_sim(
        sim_naive,
        'Naive'
    )

])

