import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

df_inv = pd.read_csv('/content/sample_data/inventory_simulation_data_model.csv')

df_inv['date'] = pd.to_datetime(df_inv['date'], errors='coerce')
df_inv = df_inv.sort_values(['category', 'date']).reset_index(drop=True)

print(df_inv.head())
print(df_inv[['date','category','sales','y_pred','y_naive']].describe(include='all'))

initial_inventory = 300
lead_time_days = 7
holding_cost_per_unit = 2
stockout_cost_per_unit = 5
safety_stock_units = 200

def infer_avg_step_days(df_cat):
    date_diffs = df_cat['date'].diff().dt.total_seconds() / (3600 * 24)
    avg_days = float(date_diffs.dropna().mean())
    if np.isnan(avg_days) or avg_days <= 0:
        avg_days = 7.0
    return avg_days


def simulate_base_stock_calendar_lead(df_in, pred_col, safety_stock):
    df_out_list = []

    for cat_val, df_cat in df_in.groupby('category', sort=False):
        df_cat = df_cat.sort_values('date').reset_index(drop=True)
        avg_step_days = infer_avg_step_days(df_cat)
        lt_steps_equiv = float(lead_time_days) / float(avg_step_days)

        inv_level = float(initial_inventory)
        open_orders = []  # [{'arrival_date': Timestamp, 'qty': float}]

        inv_levels = []
        stockout_units_list = []
        fulfilled_units_list = []
        holding_cost_list = []
        stockout_cost_list = []
        orders_placed_list = []
        receipts_list = []
        inv_position_list = []
        target_list = []
        on_order_qty_list = []

        for t_idx in range(len(df_cat)):
            current_date = df_cat.loc[t_idx, 'date']

            # Received Quantity
            received_qty = 0.0
            if open_orders:
                still_open = []
                for ord_rec in open_orders:
                    if ord_rec['arrival_date'] <= current_date:
                        received_qty += float(ord_rec['qty'])
                    else:
                        still_open.append(ord_rec)
                open_orders = still_open

            inv_level += received_qty
            receipts_list.append(received_qty)

            sales_val = float(df_cat.loc[t_idx, 'sales'])
            pred_val = float(df_cat.loc[t_idx, pred_col])

            # FullFill Demand
            fulfilled_units = min(inv_level, sales_val)
            stockout_units = max(0.0, sales_val - inv_level)
            inv_level -= fulfilled_units

            # Costs
            holding_cost_val = inv_level * holding_cost_per_unit
            stockout_cost_val = stockout_units * stockout_cost_per_unit

            # Inventory position and target
            on_order_qty = float(sum([float(o['qty']) for o in open_orders])) if open_orders else 0.0
            inv_position = float(inv_level + on_order_qty)

            demand_over_lt = float(pred_val * lt_steps_equiv)
            target = float(demand_over_lt + safety_stock)

            # Order-up-to
            order_qty = max(0.0, target - inv_position)
            if order_qty > 0:
                arrival_date = current_date + pd.Timedelta(days=int(lead_time_days))
                open_orders.append({'arrival_date': arrival_date, 'qty': order_qty})

            orders_placed_list.append(order_qty)
            inv_levels.append(inv_level)
            stockout_units_list.append(stockout_units)
            fulfilled_units_list.append(fulfilled_units)
            holding_cost_list.append(holding_cost_val)
            stockout_cost_list.append(stockout_cost_val)
            inv_position_list.append(inv_position)
            target_list.append(target)
            on_order_qty_list.append(on_order_qty)

        df_cat_out = df_cat.copy()
        df_cat_out['model_pred_col'] = pred_col
        df_cat_out['inventory'] = inv_levels
        df_cat_out['inventory_position'] = inv_position_list
        df_cat_out['target_base_stock'] = target_list
        df_cat_out['on_order_qty'] = on_order_qty_list
        df_cat_out['received'] = receipts_list
        df_cat_out['order_placed'] = orders_placed_list
        df_cat_out['stockout_units'] = stockout_units_list
        df_cat_out['fulfilled_units'] = fulfilled_units_list
        df_cat_out['holding_cost'] = holding_cost_list
        df_cat_out['stockout_cost'] = stockout_cost_list
        df_cat_out['total_cost'] = df_cat_out['holding_cost'] + df_cat_out['stockout_cost']
        df_cat_out['safety_stock'] = float(safety_stock)


        df_out_list.append(df_cat_out)

    return pd.concat(df_out_list, ignore_index=True)

def summarize_sim(sim_df, model_name):
    total_holding = float(sim_df['holding_cost'].sum())
    total_stockout_cost = float(sim_df['stockout_cost'].sum())
    total_stockout_units = float(sim_df['stockout_units'].sum())
    total_demand = float(sim_df['sales'].sum())
    total_cost = total_holding + total_stockout_cost
    fill_rate = 1.0 - (total_stockout_units / total_demand if total_demand > 0 else 0.0)
    return {
        'Model': model_name,
        'Safety Stock': float(sim_df['safety_stock'].iloc[0]) if len(sim_df) > 0 else np.nan,
        'Total Holding Cost': total_holding,
        'Total Stockout Cost': total_stockout_cost,
        'Total Stockouts': total_stockout_units,
        'Total Cost': total_cost,
        'Fill Rate': fill_rate
    }

def category_table(sim_df, model_name):
    grp = sim_df.groupby('category', as_index=False).agg(
        Stockouts=('stockout_units', 'sum'),
        HoldingCost=('holding_cost', 'sum'),
        StockoutCost=('stockout_cost', 'sum'),
        Demand=('sales', 'sum')
    )
    grp['Cost'] = grp['HoldingCost'] + grp['StockoutCost']
    grp['Fill Rate'] = 1.0 - (grp['Stockouts'] / grp['Demand']).replace([np.inf, -np.inf], np.nan)
    grp['Model'] = model_name
    return grp[['category','Model','Stockouts','Cost','Fill Rate']]

sim_xgb_base = simulate_base_stock_calendar_lead(df_inv, 'y_pred', safety_stock_units)
sim_naive_base = simulate_base_stock_calendar_lead(df_inv, 'y_naive', safety_stock_units)

summary_overall_base = pd.DataFrame([
    summarize_sim(sim_xgb_base, 'XGBoost (y_pred) - Base-stock'),
    summarize_sim(sim_naive_base, 'Naive (y_naive) - Base-stock')
])

category_results_base = pd.concat([
    category_table(sim_xgb_base, 'XGBoost (y_pred) - Base-stock'),
    category_table(sim_naive_base, 'Naive (y_naive) - Base-stock')
], ignore_index=True).rename(columns={'category':'Category'})

"""Plotting inventory overtime for one category(Higest demand)"""

plot_category = str(df_inv.groupby('category', as_index=False)['sales'].sum().sort_values('sales', ascending=False).iloc[0]['category'])
plot_xgb = sim_xgb_base[sim_xgb_base['category'] == plot_category].sort_values('date')
plot_naive = sim_naive_base[sim_naive_base['category'] == plot_category].sort_values('date')

plt.figure(figsize=(12, 5))
plt.plot(plot_xgb['date'], plot_xgb['inventory'], label='XGBoost inventory (Base-stock)', linewidth=2)
plt.plot(plot_naive['date'], plot_naive['inventory'], label='Naive inventory (Base-stock)', linewidth=2, linestyle='--')
plt.title('Inventory Level Over Time (Lead Time = 7 days, Base-stock + Safety Stock, Category: ' + plot_category + ')')
plt.xlabel('Date')
plt.ylabel('Ending Inventory')
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

print(summary_overall_base)
print(category_results_base.sort_values(['Category','Model']).reset_index(drop=True))

best_cost_model = summary_overall_base.loc[summary_overall_base['Total Cost'].idxmin(), 'Model']
best_fill_model = summary_overall_base.loc[summary_overall_base['Fill Rate'].idxmax(), 'Model']

stockout_risk = category_results_base.groupby('Category', as_index=False)['Stockouts'].sum().sort_values('Stockouts', ascending=False)
highest_risk_category = str(stockout_risk.iloc[0]['Category'])

print(best_cost_model)
print(best_fill_model)
print(highest_risk_category)