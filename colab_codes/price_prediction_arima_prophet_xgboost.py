series = price_by_date.copy()

# Create supervised lag features
def create_lagged(df, n_lags):
    data = pd.DataFrame({'y': df.values}, index=df.index)
    for i in range(1, n_lags + 1):
        data['lag_' + str(i)] = data['y'].shift(i)
    data = data.dropna()
    return data

lagged = create_lagged(series, n_lags=7)

# Train-test split (last 20% as test)
split_idx = int(len(lagged) * 0.8)
train, test = lagged.iloc[:split_idx], lagged.iloc[split_idx:]
X_train, y_train = train.drop('y', axis=1), train['y']
X_test, y_test = test.drop('y', axis=1), test['y']

