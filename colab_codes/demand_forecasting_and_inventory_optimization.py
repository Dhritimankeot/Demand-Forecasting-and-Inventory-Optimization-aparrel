plt.plot(agg_resid['date'], agg_resid['resid_xgb'], label='XGBoost residual (sum)', linewidth=2)
plt.plot(agg_resid['date'], agg_resid['resid_naive'], label='Naive residual (sum)', linewidth=1.5, alpha=0.85)
plt.title('Residuals over time (Test set, summed across categories)')
plt.xlabel('Date')
plt.ylabel('Residual = Actual - Predicted')
plt.grid(True, alpha=0.3)
