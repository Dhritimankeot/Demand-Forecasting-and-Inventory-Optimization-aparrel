inv_base['date'] = pd.to_datetime(inv_base['date'], errors='coerce')
inv_base = inv_base.dropna(subset=['date','category','actual','pred_xgb']).copy()
inv_base['actual'] = pd.to_numeric(inv_base['actual'], errors='coerce')
inv_base['pred_xgb'] = pd.to_numeric(inv_base['pred_xgb'], errors='coerce')
inv_base = inv_base.dropna(subset=['actual','pred_xgb']).copy()

print(inv_base.head())
print(inv_base['category'].value_counts())

"""Per Category Uncertainity stats"""

inv_base['residual'] = inv_base['actual'] - inv_base['pred_xgb']
inv_base['abs_residual'] = inv_base['residual'].abs()

resid_stats = inv_base.groupby('category', as_index=False).agg(
    avg_demand=('actual','mean'),
    total_demand=('actual','sum'),
    sigma=('residual','std'),
    tail_risk=('abs_residual', lambda s: float(pd.Series(s).quantile(0.95)))
)

"""Safety Stock (Normal Variation + tail"""

z = 1.65
lead_time = 1
resid_stats['ss_sigma'] = z * resid_stats['sigma'] * np.sqrt(lead_time)
resid_stats['safety_stock'] = np.maximum(resid_stats['ss_sigma'], resid_stats['tail_risk'])

"""Reorder Point"""

resid_stats['reorder_point'] = (resid_stats['avg_demand'] * lead_time) + resid_stats['safety_stock']

"""EOQ"""

ordering_cost = 500
holding_cost = 2
resid_stats['EOQ'] = np.sqrt((2.0 * resid_stats['total_demand'] * ordering_cost) / holding_cost)

"""Summary Table"""

summary_tbl = resid_stats[['category','avg_demand','sigma','tail_risk','safety_stock','reorder_point','EOQ']].copy()

for col in ['avg_demand','sigma','tail_risk','safety_stock','reorder_point','EOQ']:
    summary_tbl[col] = summary_tbl[col].round(2)

summary_tbl = summary_tbl.sort_values('reorder_point', ascending=False).reset_index(drop=True)
print(summary_tbl)

"""#incorporating tail risk aware safety stock

"""

resid_stats['ss_sigma_only'] = z * resid_stats['sigma'] * np.sqrt(lead_time)

resid_stats['safety_stock'] = np.maximum(resid_stats['ss_sigma_only'], resid_stats['tail_risk'])
resid_stats['reorder_point'] = (resid_stats['avg_demand'] * lead_time) + resid_stats['safety_stock']
resid_stats['tail_to_sigma_ratio'] = resid_stats['tail_risk'] / resid_stats['ss_sigma_only']

out_df = resid_stats[['category','avg_demand','sigma','tail_risk','safety_stock','reorder_point','EOQ']].copy()
for c in ['avg_demand','sigma','tail_risk','safety_stock','reorder_point','EOQ']:
    out_df[c] = out_df[c].round(2)

diag_df = resid_stats[['category','ss_sigma_only','tail_risk','tail_to_sigma_ratio','safety_stock']].copy()
for c in ['ss_sigma_only','tail_risk','tail_to_sigma_ratio','safety_stock']:
    diag_df[c] = diag_df[c].round(4)

